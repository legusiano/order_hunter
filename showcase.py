"""Витрина: фабрика собирает примеры ботов, которые чаще всего заказывают, — их показывает продавец и они идут
в посты канала. Сборки лежат в builds/order_<номер> (номера 9001+, в базе заказов их нет).

Собрать заново: python showcase.py
"""

import asyncio

import factory

EXAMPLES = {
    9001: ("Бот записи в салон красоты",
           "1. /start — приветствие и меню: «Записаться», «Мои записи», «Услуги и цены».\n"
           "2. Услуги с ценой и длительностью, 2 мастера, у каждого свой график работы.\n"
           "3. Клиент выбирает услугу, мастера, дату и видит только свободное время; запись подтверждается.\n"
           "4. Напоминание клиенту за 24 часа и за 2 часа до визита с кнопками «Приду» / «Отменить».\n"
           "5. Отмена освобождает время.\n"
           "6. Админка для ADMIN_IDS: записи на сегодня и завтра, отменить запись, закрыть время вручную, "
           "добавить или изменить услугу."),
    9002: ("Бот предзаказа для кофейни",
           "1. /start — меню по категориям (кофе, чай, выпечка) с ценами, кнопки.\n"
           "2. Корзина: добавить, убрать, изменить количество, итоговая сумма.\n"
           "3. Оформление: имя и время, к которому забрать заказ (через 15/30/45 минут или своё время).\n"
           "4. Новый заказ мгновенно приходит администраторам с кнопками «Принят», «Готов», «Выдан».\n"
           "5. Клиенту приходят статусы заказа; кнопка «Повторить прошлый заказ».\n"
           "6. Админ командами добавляет, меняет и скрывает позиции меню."),
    9003: ("ИИ-консультант для бизнеса",
           "1. /start — приветствие и кнопки «Задать вопрос», «Позвать менеджера».\n"
           "2. Отвечает на вопросы клиентов по базе знаний — текстовый файл knowledge.txt (цены, адреса, "
           "условия), через любой OpenAI-совместимый API (адрес, модель и ключ в .env); если ключа нет — "
           "отвечает подходящим фрагментом из базы знаний по ключевым словам.\n"
           "3. Если ответа нет в базе или клиент просит человека — передаёт вопрос менеджерам (ADMIN_IDS), "
           "менеджер отвечает командой /reply <id> <текст>, ответ приходит клиенту.\n"
           "4. Помнит последние 10 сообщений разговора с каждым клиентом.\n"
           "5. Админ командой /stats видит, сколько вопросов было и сколько передано менеджеру."),
}


async def main():
    for order_id, (title, spec) in EXAMPLES.items():
        async def say(text, order_id=order_id):
            print(f"[{order_id}] {text}", flush=True)
        try:
            result = await factory.build(order_id, title, spec, progress=say)
            print(f"[{order_id}] ✅ {title}: попыток {result['attempts']}, тестов {result['tests']}", flush=True)
        except factory.BuildError as e:
            print(f"[{order_id}] ❌ {title}: {e}"[:600], flush=True)


if __name__ == "__main__":
    asyncio.run(main())
